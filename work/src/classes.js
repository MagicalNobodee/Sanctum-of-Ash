export const DEFAULT_CLASS_ID = 'ember_paladin';

export const CLASS_BY_ID = Object.fromEntries(HERO_CLASSES.map((c) => [c.id, c]));
export const CATEGORY_BY_ID = Object.fromEntries(CLASS_CATEGORIES.map((c) => [c.id, c]));

export function getHeroClass(classId) {
  return CLASS_BY_ID[classId] || CLASS_BY_ID[DEFAULT_CLASS_ID] || HERO_CLASSES[0];
}

export function getClassText(clsOrId) {
  const cls = typeof clsOrId === 'string' ? getHeroClass(clsOrId) : (clsOrId || getHeroClass(DEFAULT_CLASS_ID));
  const cat = CATEGORY_BY_ID[cls.categoryId] || CLASS_CATEGORIES[0];
  const zh = getLang() === 'zh';
  return {
    id: cls.id,
    accent: cls.accent,
    accentHex: cls.accentHex,
    badge: zh ? cls.badge : cls.enBadge,
    name: zh ? cls.zhName : cls.enName,
    title: zh ? cls.zhTitle : cls.enTitle,
    lore: zh ? cls.zhLore : cls.enLore,
    catName: zh ? cat.zhName : cat.enName,
    catSub: zh ? cat.zhSub : cat.enSub,
    catIcon: cat.icon,
    passiveName: zh ? cls.passive.zhName : cls.passive.enName,
    passiveDesc: zh ? cls.passive.zhDesc : cls.passive.enDesc,
    activeName: zh ? cls.active.zhName : cls.active.enName,
    activeShort: zh ? cls.active.zhShort : cls.active.enShort,
    activeDesc: zh ? cls.active.zhDesc : cls.active.enDesc,
    activeCd: cls.active.cd
  };
}
